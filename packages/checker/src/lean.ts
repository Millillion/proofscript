// Driving Lean as an untrusted proof engine (decision D30).

import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";
import type { GeneratedDecl } from "./translate.ts";

/** The Lean version ProofScript's kernel is tested against (Lean Kernel Arena). */
export const LEAN_TOOLCHAIN = "leanprover/lean4:v4.34.1";
const LEAN4EXPORT_REPO = "https://github.com/leanprover/lean4export";
/** The lean4export commit known to build with LEAN_TOOLCHAIN (as the Lean Kernel Arena builds it). */
export const LEAN4EXPORT_COMMIT = "df81913eee5519d5a88ae5b0fd701b5298cc29ab";

/** Lean's tools (`lake`) on PATH, adding elan's default location if needed. */
export function leanEnv(): NodeJS.ProcessEnv {
  const elanBin = join(homedir(), ".elan", "bin");
  const path = process.env.PATH ?? "";
  return path.split(":").includes(elanBin) ? { ...process.env } : { ...process.env, PATH: `${path}:${elanBin}` };
}

/** Whether Lean's build tool is available (needed to prove, not to check certificates). */
export function leanAvailable(): boolean {
  const r = spawnSync("lake", ["--version"], { env: leanEnv(), encoding: "utf8" });
  return r.status === 0;
}
const MODULE = "PSGen";

export interface LeanMessage {
  readonly line: number;
  readonly column: number;
  readonly severity: "error" | "warning" | "info";
  readonly text: string;
}

export interface LeanBuild {
  readonly ok: boolean;
  readonly messages: LeanMessage[];
  /** Line (1-based) where each declaration starts in the generated file. */
  readonly lines: Map<GeneratedDecl, number>;
  readonly source: string;
}

function run(cmd: string, args: string[], cwd: string): { status: number; out: string } {
  const r = spawnSync(cmd, args, { cwd, encoding: "utf8", maxBuffer: 1 << 30, env: leanEnv() });
  if (r.error !== undefined) {
    throw new Error(`failed to run ${cmd}: ${r.error.message}. Proving needs Lean: install elan from https://lean-lang.org/install (the pinned toolchain is then installed automatically)`);
  }
  return { status: r.status ?? 1, out: `${r.stdout ?? ""}${r.stderr ?? ""}` };
}

export function generateSource(decls: readonly GeneratedDecl[]): { source: string; lines: Map<GeneratedDecl, number> } {
  const lines = new Map<GeneratedDecl, number>();
  let src = "-- Generated by ProofScript from TypeScript sources. Do not edit.\n\n";
  for (const d of decls) {
    lines.set(d, src.split("\n").length);
    src += `${d.source}\n\n`;
  }
  return { source: src, lines };
}

export function buildLean(workDir: string, decls: readonly GeneratedDecl[]): LeanBuild {
  mkdirSync(workDir, { recursive: true });
  writeFileSync(join(workDir, "lean-toolchain"), `${LEAN_TOOLCHAIN}\n`);
  writeFileSync(join(workDir, "lakefile.toml"), `name = "${MODULE}"\ndefaultTargets = ["${MODULE}"]\n\n[[lean_lib]]\nname = "${MODULE}"\n`);
  const { source, lines } = generateSource(decls);
  writeFileSync(join(workDir, `${MODULE}.lean`), source);
  const r = run("lake", ["build"], workDir);
  const messages: LeanMessage[] = [];
  // Lake prints `error: ./PSGen.lean:12:4: message`, possibly followed by more lines.
  const head = /^(error|warning|info): (?:\.\/)?PSGen\.lean:(\d+):(\d+): ?(.*)$/;
  const boundary = /^(error|warning|info|trace):|^[✖⚠✔]|^Some required|^Build|^Error:/;
  let cur: { line: number; column: number; severity: LeanMessage["severity"]; text: string[] } | undefined;
  const flush = (): void => {
    if (cur !== undefined) messages.push({ line: cur.line, column: cur.column, severity: cur.severity, text: cur.text.join("\n").trim() });
    cur = undefined;
  };
  for (const l of r.out.split("\n")) {
    const m = head.exec(l);
    if (m !== null) {
      flush();
      cur = { line: Number(m[2]), column: Number(m[3]), severity: m[1] as LeanMessage["severity"], text: [m[4] ?? ""] };
    } else if (boundary.test(l)) {
      flush();
    } else if (cur !== undefined) {
      cur.text.push(l);
    }
  }
  flush();
  if (r.status !== 0 && messages.every((m) => m.severity !== "error")) {
    messages.push({ line: 1, column: 1, severity: "error", text: r.out.trim().split("\n").slice(-20).join("\n") });
  }
  return { ok: r.status === 0, messages, lines, source };
}

/** Finds or builds lean4export (pinned to the toolchain), returning the binary path. */
export function ensureLean4export(): string {
  const env = process.env.PROOFSCRIPT_LEAN4EXPORT;
  if (env !== undefined && existsSync(env)) return env;
  const dir = join(homedir(), ".cache", "proofscript", `lean4export-${LEAN_TOOLCHAIN.replace(/[^A-Za-z0-9.]/g, "_")}`);
  const bin = join(dir, ".lake", "build", "bin", "lean4export");
  if (existsSync(bin)) return bin;
  if (!existsSync(dir)) {
    mkdirSync(join(homedir(), ".cache", "proofscript"), { recursive: true });
    const r = run("git", ["clone", "--quiet", LEAN4EXPORT_REPO, dir], homedir());
    if (r.status !== 0) throw new Error(`failed to clone lean4export: ${r.out}`);
    const c = run("git", ["checkout", "--quiet", LEAN4EXPORT_COMMIT], dir);
    if (c.status !== 0) throw new Error(`failed to check out lean4export ${LEAN4EXPORT_COMMIT}: ${c.out}`);
  }
  writeFileSync(join(dir, "lean-toolchain"), `${LEAN_TOOLCHAIN}\n`);
  const b = run("lake", ["build"], dir);
  if (b.status !== 0 || !existsSync(bin)) throw new Error(`failed to build lean4export:\n${b.out}`);
  return bin;
}

/** Exports the given declarations (and everything they depend on) as NDJSON. */
export function exportDecls(workDir: string, names: readonly string[]): string {
  const bin = ensureLean4export();
  const out = join(workDir, "export.ndjson");
  const r = spawnSync("lake", ["env", bin, MODULE, "--", ...names], {
    cwd: workDir,
    encoding: "utf8",
    maxBuffer: 1 << 30,
    env: leanEnv(),
  });
  if (r.status !== 0) throw new Error(`lean4export failed: ${r.stderr}`);
  writeFileSync(out, r.stdout);
  return readFileSync(out, "utf8");
}
